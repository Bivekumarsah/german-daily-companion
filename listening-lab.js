/* Three short listen-first rounds, using existing curated or original A1 vocabulary.
   Device German speech is optional; this is self-study, not an exam score. */
(() => {
  'use strict';
  function el(tag, className, text) {
    const n = document.createElement(tag);
    if(className)n.className=className;
    if(text!==undefined)n.textContent=text;
    return n;
  }
  function button(text, callback, className='visual-lab-small-btn') {
    const n=el('button',className,text);
    n.type='button';
    n.addEventListener('click',callback);
    return n;
  }
  // Use only distinct, unambiguous English options; the original lesson is not altered.
  function usable(items) {
    return Array.isArray(items) && items.length===3 &&
      items.every(x=>Array.isArray(x) && x.length>=4 && [x[1],x[2],x[3]].every(v=>typeof v==='string'&&!!v.trim())) &&
      new Set(items.map(x=>x[2].trim().toLocaleLowerCase('en'))).size===3 &&
      new Set(items.map(x=>x[1].trim().toLocaleLowerCase('de'))).size===3;
  }
  function render(host, unit, items, speak) {
    if(!host || !unit || !usable(items) || typeof speak!=='function')return false;

    const ear=el('details','visual-lab-ears');
    const summary=el('summary','visual-lab-story-head','🎧 Listen, choose & repeat — 3 quick rounds');
    ear.append(summary);
    const instructions=el('p','visual-lab-story-tip',
      'First listen, then choose the English meaning. No German word is shown before you answer. Press slow to hear it again.');
    ear.append(instructions);
    const audioHelp=el('p','visual-lab-ear-help','If you cannot hear German, select or install a German voice in your device settings. Audio is generated by your device and is not official exam audio.');
    ear.append(audioHelp);
    const progress=el('p','visual-lab-ear-progress','');
    progress.setAttribute('role','status');
    const actionRow=el('div','visual-lab-turn-actions');
    const play=button('🔊 Hear word',()=>speak(items[order[index]][1],false));
    const slow=button('◷ Hear slowly',()=>speak(items[order[index]][1],true));
    actionRow.append(play,slow);
    const options=el('div','visual-lab-options');
    options.setAttribute('role','group');
    options.setAttribute('aria-label','Choose the English meaning of the spoken German word');
    const result=el('p','visual-lab-feedback','');
    result.setAttribute('role','status');
    result.setAttribute('aria-live','polite');
    const revealed=el('div','visual-lab-ear-reveal');
    revealed.hidden=true;
    const continueButton=button('Next listening round →',advance,'secondary-btn visual-lab-ear-next');
    continueButton.hidden=true;
    ear.append(progress,actionRow,options,result,revealed,continueButton);
    const order=[1,2,0]; // Each of the three words is heard exactly once.
    let index=0;
    let successes=0;
    let answered=false;

    function round() {
      answered=false;
      const current=items[order[index]];
      progress.textContent='Listening round '+(index+1)+' of '+order.length;
      options.replaceChildren();
      result.textContent='';
      revealed.replaceChildren();
      revealed.hidden=true;
      continueButton.hidden=true;
      // Vary answer placement to avoid making it easy to guess a consistent position.
      const offset=(index*2+(Number(unit.number)||0))%items.length;
      const choices=items.map((_,i)=>items[(i+offset)%items.length]);
      for(const candidate of choices) {
        const choice=button(candidate[2],()=>{
          if(answered)return;
          answered=true;
          const correct=candidate===current;
          if(correct)successes++;
          for(const option of options.children)option.disabled=true;
          choice.classList.add(correct?'visual-lab-correct':'visual-lab-try-again');
          if(!correct) {
            const correctChoice=Array.from(options.children).find(opt=>opt.textContent===current[2]);
            if(correctChoice)correctChoice.classList.add('visual-lab-correct');
          }
          result.textContent=correct?'✓ Correct! Listen and repeat the German word aloud.':
            'Not quite. The correct English meaning is '+current[2]+'. Replay and repeat the German word aloud.';
          const sentence=el('strong','visual-lab-ear-german',current[1]);sentence.lang='de';
          revealed.append(sentence,el('p','',current[2]+' · '+current[3]));
          if(current[4]&&current[5])revealed.append(el('small','', 'Approximate sounds: '+current[4]+' · '+current[5]));
          const reminder=el('small','','Device-generated German voice. These sounds may vary by your installed voice.');
          revealed.append(reminder);
          revealed.hidden=false;
          continueButton.textContent=index===order.length-1?'Finish listening practice →':'Next listening round →';
          continueButton.hidden=false;
        },'visual-lab-option');
        options.append(choice);
      }
    }
    function advance() {
      if(index>=order.length) {
        index=0;successes=0;actionRow.hidden=false;round();return;
      }
      if(!answered)return;
      index++;
      if(index<order.length){round();return;}
      options.replaceChildren();
      revealed.hidden=true;
      actionRow.hidden=true;
      progress.textContent='🎉 Listening practice complete';
      result.textContent='You recognised '+successes+' of '+order.length+' words on the first choice. Revisit any word and practise speaking aloud.';
      continueButton.textContent='Try all 3 rounds again ↻';
      continueButton.hidden=false;
      // Keep the practice score separate from stored unit completion and Goethe results.
    }
    round();
    host.append(ear);
    return true;
  }
  window.DEUTSCH_LISTENING_LAB={render,usable};
})();